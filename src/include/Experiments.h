// The OR-Library groups a and b (n <= 200) and the groups c, d and e of Yagiura
// (types c and d with n <= 200 are those of the OR-Library; the larger ones and
// type e were generated by Yagiura and coauthors), and the real instance.
inline std::vector<InstanceInfo> instances() {
    std::vector<InstanceInfo> list;
    auto add = [&](char group, std::vector<std::string> sizes) {
        for (const std::string& size : sizes) {
            std::string name = std::string(1, group) + size;
            list.push_back({std::string("instances/gap/gap_") + group + "/" + name, name, group,
                            std::stoi(size.substr(2))});
        }
    };
    add('a', {"05100", "05200", "10100", "10200", "20100", "20200"});
    add('b', {"05100", "05200", "10100", "10200", "20100", "20200"});
    const std::vector<std::string> large = {"05100", "05200", "10100", "10200", "10400", "20100", "20200",
                                            "20400", "40400", "15900", "30900", "60900", "201600",
                                            "401600", "801600"};
    add('c', large);
    add('d', large);
    add('e', large);
    list.push_back({"instances/real/real_instance", "real", 'r', 1100});
    return list;
}

// largest seller-warehouse cost (as in the algorithms)
inline double largest_cost(const Instance& inst) {
    double m = 0;
    for (const auto& row : inst.cost)
        for (double c : row) m = std::max(m, c);
    return m;
}

// total cost recomputed from scratch (penalized objective of the report): the
// assigned distances plus 3 * largest cost for each unassigned seller.
inline double evaluate(const Solution& sol, const Instance& inst) {
    double penalty = 3 * largest_cost(inst);
    double total = 0;
    for (int j = 0; j < (int)inst.sellers.size(); j++) {
        int w = sol.assigned_warehouse[j];
        total += w < 0 ? penalty : inst.cost[j][w];
    }
    return total;
}

inline int unassigned(const Solution& sol) {
    int count = 0;
    for (int w : sol.assigned_warehouse) count += w < 0;
    return count;
}

// mean distance of the sellers that are actually assigned
inline double mean_distance(const Solution& sol, const Instance& inst) {
    double sum = 0;
    int assigned = 0;
    for (int j = 0; j < (int)inst.sellers.size(); j++) {
        int w = sol.assigned_warehouse[j];
        if (w >= 0) { sum += inst.cost[j][w]; assigned++; }
    }
    return assigned > 0 ? sum / assigned : 0;
}

// no capacity is exceeded (with the demand d_ij of each seller in its warehouse)
// and the two views of the assignment (assigned_warehouse, sellers_per_warehouse)
// agree.
inline bool feasible(const Solution& sol, const Instance& inst) {
    int m = inst.warehouses.size();
    int n = inst.sellers.size();
    std::vector<int> used(m, 0);
    for (int j = 0; j < n; j++) {
        int w = sol.assigned_warehouse[j];
        if (w >= 0) used[w] += inst.demand(j, w);
    }
    for (int i = 0; i < m; i++)
        if (used[i] > inst.warehouses[i].capacity) return false;
    std::vector<int> count(n, 0);
    for (int i = 0; i < m; i++)
        for (int j : sol.sellers_per_warehouse[i]) {
            if (sol.assigned_warehouse[j] != i) return false;
            count[j]++;
        }
    for (int j = 0; j < n; j++) {
        if (count[j] != (sol.assigned_warehouse[j] >= 0 ? 1 : 0)) return false;
    }
    return true;
}

// seconds taken by f()
template <class F>
double timed(F&& f) {
    auto t0 = std::chrono::high_resolution_clock::now();
    f();
    auto t1 = std::chrono::high_resolution_clock::now();
    return std::chrono::duration_cast<std::chrono::microseconds>(t1 - t0).count() / 1e6;
}

// time budget (seconds) of the metaheuristics, by size
inline double time_budget(int n) {
    if (n <= 200) return 2.0;     // small
    if (n <= 900) return 10.0;    // medium
    return 60.0;                  // large (real, e*1600)
}

