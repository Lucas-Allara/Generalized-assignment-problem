// destruction size of the LNS: in the tuning, the small instances do better with a
// small destruction (20) and the real one with a large one (100). On e15900
// (n = 900) 100 is 0.4% better, but there the LNS stays about four times above the
// optimum, held back by the VND of its starting solution, so the threshold is kept.
inline int lns_destroy(int n) { return n > 900 ? 100 : 20; }

// summary statistics of a set of costs (best, worst, mean, standard deviation)
struct Stats { double best, worst, mean, std_dev; };
inline Stats summarize(const std::vector<double>& v) {
    Stats s{0, 0, 0, 0};
    if (v.empty()) return s;
    s.best = *std::min_element(v.begin(), v.end());
    s.worst = *std::max_element(v.begin(), v.end());
    s.mean = std::accumulate(v.begin(), v.end(), 0.0) / v.size();
    double acc = 0;
    for (double x : v) acc += (x - s.mean) * (x - s.mean);
    s.std_dev = std::sqrt(acc / v.size());
    return s;
}

